"""Generate the flatbuffers schema and the benchmark codecs from
schema/emc_stat.schema.json, so every encoding works on the same fields.

Outputs (into OUTDIR):
    emc_stat.fbs        flatbuffers schema: table EmcStat (full update) and
                        table EmcStatDelta (every field optional; absent =
                        unchanged), 9-element poses as struct Pose from
                        rmu75's emc_common.fbs
    emc_common.fbs      copy of rmu75's emc_common.fbs (Pose, Cartesian)
    emc_native.hh       C++: struct EmcStat (+ nested structs), nlohmann
                        to_json/from_json, flatbuffers pack/unpack and
                        pack_delta/apply_delta
    fb_codec.py         Python: pack(dict)->bytes, unpack(bytes)->dict,
                        pack_delta(prev, cur)->bytes|None, apply_delta(bytes, dict)

usage: gen_codecs.py OUTDIR
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# 9-element positions -> struct Pose (rmu75 emc_common.fbs)
POSE_FIELDS = {"actual_position", "position", "dtg", "g5x_offset", "g92_offset",
               "tool_offset", "probed_position", "g68_offset"}
POSE_AXES = ("x", "y", "z", "a", "b", "c", "u", "v", "w")
LONG_INTS = {"heartbeat", "taskbeat"}
CPP_KEYWORDS = {"state", "debug", "input", "output", "index", "count"}


def fb_name(k):
    """flatbuffers field name: snake_case (jointType -> joint_type)."""
    out = ""
    for ch in k:
        if ch.isupper():
            out += "_" + ch.lower()
        else:
            out += ch
    return out


def py_method(k):
    """Python accessor generated by flatc for field k."""
    return "".join(p[:1].upper() + p[1:] for p in fb_name(k).split("_"))


def cpp_field(k):
    return fb_name(k)


def table_name(k):
    return {"joint": "JointStat", "axis": "AxisStat", "spindle": "SpindleStat",
            "tool_table": "ToolEntry", "call_stack": "CallFrame"}[k]


class Field:
    def __init__(self, key, sch):
        self.key = key
        self.name = fb_name(key)
        t = sch.get("type")
        self.kind = None
        if t == "integer":
            self.kind = "long" if key in LONG_INTS else "int"
        elif t == "number":
            self.kind = "double"
        elif t == "boolean":
            self.kind = "bool"
        elif t == "string":
            self.kind = "string"
        elif t == "array":
            it = sch["items"]
            if key in POSE_FIELDS:
                self.kind = "pose"
            elif it.get("type") == "object":
                self.kind = "table_vec"
                self.table = table_name(key)
                self.sub = [Field(k, v) for k, v in it["properties"].items()]
            elif it.get("type") == "integer":
                self.kind = "int_vec"
            elif it.get("type") == "number":
                self.kind = "double_vec"
            else:
                raise ValueError(key)
        else:
            raise ValueError((key, t))

    @property
    def scalar(self):
        return self.kind in ("int", "long", "double", "bool")


def load_fields():
    with open(os.path.join(ROOT, "schema", "emc_stat.schema.json")) as f:
        sch = json.load(f)
    return [Field(k, v) for k, v in sch["properties"].items()]


# ------------------------------------------------------------------ fbs
FB_TYPES = {"int": "int", "long": "long", "double": "double", "bool": "bool",
            "string": "string", "int_vec": "[int]", "double_vec": "[double]",
            "pose": "Pose"}


def gen_fbs(fields):
    out = ["// Generated by bench/gen_codecs.py from schema/emc_stat.schema.json.",
           "// Field set and names: linuxcnc.stat (the benchmark input).",
           "// Pose: rmu75 rs/zmq-experiments src/emc/flatbuf/emc_common.fbs (GPL-2.0).",
           "// Table layout per rmu75 emc_stat.fbs idea (JointStat/AxisStat/SpindleStat),",
           "// but fields follow linuxcnc.stat, not the EMC_STAT C struct.",
           'include "emc_common.fbs";', "", "namespace EMC;", ""]
    subs = [f for f in fields if f.kind == "table_vec"]
    for f in subs:
        out.append("table %s {" % f.table)
        for s in f.sub:
            out.append("  %s: %s;" % (s.name, FB_TYPES[s.kind]))
        out.append("}")
        out.append("")
    for root, opt in (("EmcStat", False), ("EmcStatDelta", True)):
        out.append("table %s {" % root)
        if opt:
            out.append("  // every field optional: absent = unchanged since the previous update")
        for f in fields:
            t = FB_TYPES.get(f.kind) or "[%s]" % f.table
            dflt = " = null" if opt and f.scalar else ""
            out.append("  %s: %s%s;" % (f.name, t, dflt))
        out.append("}")
        out.append("")
    out.append("root_type EmcStat;")
    return "\n".join(out) + "\n"


# ------------------------------------------------------------------ C++
CPP_T = {"int": "int32_t", "long": "int64_t", "double": "double", "bool": "bool",
         "string": "std::string", "int_vec": "std::vector<int32_t>",
         "double_vec": "std::vector<double>", "pose": "std::array<double, 9>"}


def cpp_type(f):
    return CPP_T.get(f.kind) or "std::vector<%s>" % f.table


def gen_cpp(fields):
    o = ["// Generated by bench/gen_codecs.py from schema/emc_stat.schema.json -- do not edit.",
         "#pragma once", "#include <array>", "#include <cstdint>", "#include <string>",
         "#include <vector>", "#include <nlohmann/json.hpp>", '#include "emc_stat_generated.h"', "",
         "namespace native {", "using nlohmann::json;", ""]
    subs = [f for f in fields if f.kind == "table_vec"]
    for f in subs:
        o.append("struct %s {" % f.table)
        for s in f.sub:
            o.append("    %s %s{};" % (cpp_type(s), cpp_field(s.key)))
        o.append("    bool operator==(const %s&) const = default;" % f.table)
        o.append("};")
    o.append("struct EmcStat {")
    for f in fields:
        o.append("    %s %s{};" % (cpp_type(f), cpp_field(f.key)))
    o.append("    bool operator==(const EmcStat&) const = default;")
    o.append("};")
    o.append("")
    # json
    for st, flist in [(f.table, f.sub) for f in subs] + [("EmcStat", fields)]:
        o.append("inline void to_json(json& j, const %s& s) {" % st)
        o.append("    j = json::object();")
        for f in flist:
            o.append('    j["%s"] = s.%s;' % (f.key, cpp_field(f.key)))
        o.append("}")
        o.append("inline void from_json(const json& j, %s& s) {" % st)
        for f in flist:
            o.append('    j.at("%s").get_to(s.%s);' % (f.key, cpp_field(f.key)))
        o.append("}")
    # flatbuffers pack
    o.append("")
    o.append("inline EMC::Pose to_pose(const std::array<double, 9>& p) {")
    o.append("    return EMC::Pose(p[0], p[1], p[2], p[3], p[4], p[5], p[6], p[7], p[8]);")
    o.append("}")
    o.append("inline void from_pose(const EMC::Pose* p, std::array<double, 9>& a) {")
    o.append("    a = {p->x(), p->y(), p->z(), p->a(), p->b(), p->c(), p->u(), p->v(), p->w()};")
    o.append("}")
    for f in subs:
        o.append("inline flatbuffers::Offset<EMC::%s> pack(flatbuffers::FlatBufferBuilder& b, const %s& s) {"
                 % (f.table, f.table))
        pre = []
        for s in f.sub:
            if s.kind == "string":
                pre.append("    auto o_%s = b.CreateString(s.%s);" % (s.name, cpp_field(s.key)))
        o += pre
        o.append("    EMC::%sBuilder t(b);" % f.table)
        for s in f.sub:
            v = "o_%s" % s.name if s.kind == "string" else "s.%s" % cpp_field(s.key)
            o.append("    t.add_%s(%s);" % (s.name, v))
        o.append("    return t.Finish();")
        o.append("}")
        o.append("inline void unpack(const EMC::%s* t, %s& s) {" % (f.table, f.table))
        for s in f.sub:
            if s.kind == "string":
                o.append("    s.%s = t->%s() ? t->%s()->str() : std::string();" % (cpp_field(s.key), s.name, s.name))
            else:
                o.append("    s.%s = t->%s();" % (cpp_field(s.key), s.name))
        o.append("}")

    def vec_offsets(cond_prefix, root_args):
        lines = []
        for f in fields:
            c = cpp_field(f.key)
            cond = cond_prefix.format(c=c)
            if f.kind == "string":
                lines.append("    flatbuffers::Offset<flatbuffers::String> o_%s;%s o_%s = b.CreateString(cur.%s);"
                             % (f.name, cond, f.name, c))
            elif f.kind in ("int_vec", "double_vec"):
                et = "int32_t" if f.kind == "int_vec" else "double"
                lines.append("    flatbuffers::Offset<flatbuffers::Vector<%s>> o_%s;%s o_%s = b.CreateVector(cur.%s);"
                             % (et, f.name, cond, f.name, c))
            elif f.kind == "table_vec":
                lines.append("    flatbuffers::Offset<flatbuffers::Vector<flatbuffers::Offset<EMC::%s>>> o_%s;%s {"
                             % (f.table, f.name, cond))
                lines.append("        std::vector<flatbuffers::Offset<EMC::%s>> v; v.reserve(cur.%s.size());" % (f.table, c))
                lines.append("        for (auto& e : cur.%s) v.push_back(pack(b, e));" % c)
                lines.append("        o_%s = b.CreateVector(v); }" % f.name)
        return lines

    # full
    o.append("inline void pack_full(flatbuffers::FlatBufferBuilder& b, const EmcStat& cur) {")
    o += vec_offsets("", None)
    o.append("    EMC::EmcStatBuilder t(b);")
    for f in fields:
        c = cpp_field(f.key)
        if f.kind == "pose":
            o.append("    { auto p = to_pose(cur.%s); t.add_%s(&p); }" % (c, f.name))
        elif f.scalar:
            o.append("    t.add_%s(cur.%s);" % (f.name, c))
        else:
            o.append("    t.add_%s(o_%s);" % (f.name, f.name))
    o.append("    b.Finish(t.Finish());")
    o.append("}")
    # unpack full
    o.append("inline void unpack_full(const EMC::EmcStat* t, EmcStat& s) {")
    for f in fields:
        c = cpp_field(f.key)
        if f.kind == "pose":
            o.append("    from_pose(t->%s(), s.%s);" % (f.name, c))
        elif f.scalar:
            o.append("    s.%s = t->%s();" % (c, f.name))
        elif f.kind == "string":
            o.append("    s.%s = t->%s()->str();" % (c, f.name))
        elif f.kind in ("int_vec", "double_vec"):
            o.append("    s.%s.assign(t->%s()->begin(), t->%s()->end());" % (c, f.name, f.name))
        else:
            o.append("    { auto v = t->%s(); s.%s.resize(v->size());" % (f.name, c))
            o.append("      for (flatbuffers::uoffset_t i = 0; i < v->size(); i++) unpack(v->Get(i), s.%s[i]); }" % c)
    o.append("}")
    # delta
    o.append("// returns false (nothing written) when nothing changed")
    o.append("inline bool pack_delta(flatbuffers::FlatBufferBuilder& b, const EmcStat& prev, const EmcStat& cur) {")
    o.append("    bool any = false;")
    for f in fields:
        c = cpp_field(f.key)
        o.append("    const bool ch_%s = !(prev.%s == cur.%s); any |= ch_%s;" % (f.name, c, c, f.name))
    o.append("    if (!any) return false;")
    o += vec_offsets(" if (ch_{c})", None)
    o.append("    EMC::EmcStatDeltaBuilder t(b);")
    for f in fields:
        c = cpp_field(f.key)
        if f.kind == "pose":
            o.append("    if (ch_%s) { auto p = to_pose(cur.%s); t.add_%s(&p); }" % (f.name, c, f.name))
        elif f.scalar:
            o.append("    if (ch_%s) t.add_%s(cur.%s);" % (f.name, f.name, c))
        else:
            o.append("    if (ch_%s) t.add_%s(o_%s);" % (f.name, f.name, f.name))
    o.append("    b.Finish(t.Finish());")
    o.append("    return true;")
    o.append("}")
    o.append("inline void apply_delta(const EMC::EmcStatDelta* t, EmcStat& s) {")
    for f in fields:
        c = cpp_field(f.key)
        if f.kind == "pose":
            o.append("    if (auto p = t->%s()) from_pose(p, s.%s);" % (f.name, c))
        elif f.scalar:
            o.append("    if (auto v = t->%s()) s.%s = *v;" % (f.name, c))
        elif f.kind == "string":
            o.append("    if (auto v = t->%s()) s.%s = v->str();" % (f.name, c))
        elif f.kind in ("int_vec", "double_vec"):
            o.append("    if (auto v = t->%s()) s.%s.assign(v->begin(), v->end());" % (f.name, c))
        else:
            o.append("    if (auto v = t->%s()) { s.%s.resize(v->size());" % (f.name, c))
            o.append("      for (flatbuffers::uoffset_t i = 0; i < v->size(); i++) unpack(v->Get(i), s.%s[i]); }" % c)
    o.append("}")
    o.append("}  // namespace native")
    return "\n".join(o) + "\n"


# --------------------------------------------------------------- Python
def gen_py(fields):
    subs = [f for f in fields if f.kind == "table_vec"]
    o = ['"""Generated by bench/gen_codecs.py -- flatbuffers codec over the stat dict."""',
         "import flatbuffers", "from flatbuffers import number_types as N"]
    o.append("from EMC import EmcStat as _S, EmcStatDelta as _D, Pose as _P")
    for f in subs:
        o.append("from EMC import %s as _%s" % (f.table, f.table))
    o.append("POSE = %r" % (POSE_AXES,))
    o.append("")
    # sub-table pack/unpack
    for f in subs:
        o.append("def _pack_%s(b, d):" % f.table)
        for s in f.sub:
            if s.kind == "string":
                o.append("    s_%s = b.CreateString(d[%r])" % (s.name, s.key))
        o.append("    _%s.Start(b)" % f.table)
        for s in f.sub:
            v = "s_%s" % s.name if s.kind == "string" else "d[%r]" % s.key
            o.append("    _%s.Add%s(b, %s)" % (f.table, py_method(s.key), v))
        o.append("    return _%s.End(b)" % f.table)
        o.append("def _unpack_%s(t):" % f.table)
        items = []
        for s in f.sub:
            acc = "t.%s()" % py_method(s.key)
            if s.kind == "string":
                acc = "t.%s().decode()" % py_method(s.key)
            items.append("%r: %s" % (s.key, acc))
        o.append("    return {%s}" % ", ".join(items))
    o.append("")

    def vec_lines(prefix, guard):
        L = []
        for f in fields:
            if f.kind not in ("string", "int_vec", "double_vec", "table_vec"):
                continue
            g = guard.format(k=f.key)
            ind = "    " + ("    " if g else "")
            if g:
                L.append("    if %s:" % g)
            if f.kind == "string":
                L.append(ind + "o_%s = b.CreateString(cur[%r])" % (f.name, f.key))
            elif f.kind in ("int_vec", "double_vec"):
                L.append(ind + "o_%s = b.CreateNumpyVector(_np.asarray(cur[%r], dtype=%s)) if _np else _vec(b, cur[%r], %s)"
                         % (f.name, f.key, "_np.int32" if f.kind == "int_vec" else "_np.float64", f.key,
                            "b.PrependInt32" if f.kind == "int_vec" else "b.PrependFloat64"))
            elif f.kind == "table_vec":
                L.append(ind + "_o = [_pack_%s(b, e) for e in cur[%r]]" % (f.table, f.key))
                L.append(ind + "b.StartVector(4, len(_o), 4)")
                L.append(ind + "for x in reversed(_o): b.PrependUOffsetTRelative(x)")
                L.append(ind + "o_%s = b.EndVector()" % f.name)
        return L
    o.append("try:")
    o.append("    import numpy as _np")
    o.append("except ImportError:")
    o.append("    _np = None")
    o.append("def _vec(b, xs, prep):")
    o.append("    b.StartVector(8 if prep == b.PrependFloat64 else 4, len(xs), 8 if prep == b.PrependFloat64 else 4)")
    o.append("    for x in reversed(xs): prep(x)")
    o.append("    return b.EndVector()")
    o.append("")
    o.append("def pack(cur, b=None):")
    o.append("    b = b or flatbuffers.Builder(16384)")
    o += vec_lines("", "")
    o.append("    _S.Start(b)")
    for f in fields:
        m = py_method(f.key)
        if f.kind == "pose":
            o.append("    _S.Add%s(b, _P.CreatePose(b, *cur[%r]))" % (m, f.key))
        elif f.scalar:
            o.append("    _S.Add%s(b, cur[%r])" % (m, f.key))
        else:
            o.append("    _S.Add%s(b, o_%s)" % (m, f.name))
    o.append("    b.Finish(_S.End(b))")
    o.append("    return b.Output()")
    o.append("")

    def unpack_lines(var, delta):
        L = []
        for f in fields:
            m = py_method(f.key)
            if f.kind == "pose":
                if delta:
                    L.append("    p = t.%s()" % m)
                    L.append("    if p is not None: d[%r] = [p.X(), p.Y(), p.Z(), p.A(), p.B(), p.C(), p.U(), p.V(), p.W()]" % f.key)
                else:
                    L.append("    p = t.%s(); d[%r] = [p.X(), p.Y(), p.Z(), p.A(), p.B(), p.C(), p.U(), p.V(), p.W()]" % (m, f.key))
            elif f.scalar:
                conv = "bool" if f.kind == "bool" else ""
                if delta:
                    L.append("    v = t.%s()" % m)
                    L.append("    if v is not None: d[%r] = v" % f.key)
                else:
                    L.append("    d[%r] = t.%s()" % (f.key, m))
            elif f.kind == "string":
                if delta:
                    L.append("    v = t.%s()" % m)
                    L.append("    if v is not None: d[%r] = v.decode()" % f.key)
                else:
                    L.append("    d[%r] = t.%s().decode()" % (f.key, m))
            elif f.kind in ("int_vec", "double_vec"):
                guard = "if not t.%sIsNone(): " % m if delta else ""
                L.append("    %sd[%r] = t.%sAsNumpy().tolist() if _np else [t.%s(i) for i in range(t.%sLength())]"
                         % (guard, f.key, m, m, m))
            else:
                guard = "if not t.%sIsNone(): " % m if delta else ""
                L.append("    %sd[%r] = [_unpack_%s(t.%s(i)) for i in range(t.%sLength())]"
                         % (guard, f.key, f.table, m, m))
        return L
    o.append("def unpack(buf):")
    o.append("    t = _S.EmcStat.GetRootAs(buf, 0)")
    o.append("    d = {}")
    o += unpack_lines("t", False)
    o.append("    return d")
    o.append("")
    o.append("def pack_delta(prev, cur, b=None):")
    o.append("    ch = [k for k in cur if prev.get(k) != cur[k] or type(prev.get(k)) is not type(cur[k])]")
    o.append("    if not ch: return None")
    o.append("    chs = set(ch)")
    o.append("    b = b or flatbuffers.Builder(4096)")
    o += vec_lines("", "{k!r} in chs")
    o.append("    _D.Start(b)")
    for f in fields:
        m = py_method(f.key)
        o.append("    if %r in chs:" % f.key)
        if f.kind == "pose":
            o.append("        _D.Add%s(b, _P.CreatePose(b, *cur[%r]))" % (m, f.key))
        elif f.scalar:
            o.append("        _D.Add%s(b, cur[%r])" % (m, f.key))
        else:
            o.append("        _D.Add%s(b, o_%s)" % (m, f.name))
    o.append("    b.Finish(_D.End(b))")
    o.append("    return b.Output()")
    o.append("")
    o.append("def apply_delta(buf, d):")
    o.append("    t = _D.EmcStatDelta.GetRootAs(buf, 0)")
    o += unpack_lines("t", True)
    o.append("    return d")
    return "\n".join(o) + "\n"


def main(outdir):
    os.makedirs(outdir, exist_ok=True)
    fields = load_fields()
    with open(os.path.join(outdir, "emc_stat.fbs"), "w") as f:
        f.write(gen_fbs(fields))
    src = os.path.join(ROOT, "schema", "fbs", "emc_common.fbs")
    with open(src) as fi, open(os.path.join(outdir, "emc_common.fbs"), "w") as fo:
        fo.write(fi.read())
    with open(os.path.join(outdir, "emc_native.hh"), "w") as f:
        f.write(gen_cpp(fields))
    with open(os.path.join(outdir, "fb_codec.py"), "w") as f:
        f.write(gen_py(fields))
    print("generated %d fields into %s" % (len(fields), outdir))


if __name__ == "__main__":
    main(sys.argv[1])
