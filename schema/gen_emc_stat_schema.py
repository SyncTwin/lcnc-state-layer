"""Generate schema/emc_stat.schema.json from a live linuxcnc.stat.

Run once against a running LinuxCNC (or with --from-trace on a recorded trace);
the committed schema is then the reference the sidecar, the clients and the
trace checker validate against.  Field names and nesting are exactly those of
the linuxcnc Python module (emcmodule.cc Stat_members / Stat_getsetlist).

usage: gen_emc_stat_schema.py [--from-trace traces/x.jsonl.gz] > emc_stat.schema.json
"""
import argparse
import gzip
import json
import os
import sys

DESCRIPTIONS = {
    "task_state": "EMC_TASK_STATE: STATE_ESTOP=1, STATE_ESTOP_RESET=2, STATE_OFF=3, STATE_ON=4",
    "task_mode": "EMC_TASK_MODE: MODE_MANUAL=1, MODE_AUTO=2, MODE_MDI=3",
    "interp_state": "EMC_TASK_INTERP: INTERP_IDLE=1, INTERP_READING=2, INTERP_PAUSED=3, INTERP_WAITING=4",
    "exec_state": "EMC_TASK_EXEC: EXEC_ERROR=1, EXEC_DONE=2, EXEC_WAITING_FOR_MOTION=3, ...",
    "state": "RCS status of the command echo_serial_number refers to: RCS_DONE=1, RCS_EXEC=2, RCS_ERROR=3",
    "echo_serial_number": "serial number of the last command task processed",
    "heartbeat": "motion heartbeat counter, changes every servo cycle",
    "taskbeat": "task cycle counter, changes every task cycle",
    "motion_line": "source line of the motion currently executing",
    "file": "loaded program path",
    "tool_table": "tool_result entries; index 0 is the tool in the spindle",
}


def schema_of(v, name=None):
    if isinstance(v, bool):
        s = {"type": "boolean"}
    elif isinstance(v, int):
        s = {"type": "integer"}
    elif isinstance(v, float):
        s = {"type": "number"}
    elif isinstance(v, str):
        s = {"type": "string"}
    elif isinstance(v, list):
        s = {"type": "array"}
        if v:
            items = [schema_of(x) for x in v]
            first = items[0]
            if all(i == first for i in items):
                s["items"] = first
            elif all(i.get("type") in ("integer", "number") for i in items):
                s["items"] = {"type": "number"}
            else:
                s["items"] = first
            s["minItems"] = s["maxItems"] = len(v)
    elif isinstance(v, dict):
        s = {"type": "object",
             "properties": {k: schema_of(x, k) for k, x in sorted(v.items())},
             "required": sorted(v),
             "additionalProperties": False}
    else:
        raise TypeError(type(v))
    if name in DESCRIPTIONS:
        s["description"] = DESCRIPTIONS[name]
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--from-trace")
    args = ap.parse_args()
    if args.from_trace:
        with gzip.open(args.from_trace, "rt") as f:
            f.readline()
            stat = json.loads(f.readline())["stat"]
    else:
        sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "sidecar"))
        import linuxcnc
        from lcnc_state.statdict import stat_names, stat_to_dict
        s = linuxcnc.stat()
        s.poll()
        stat = stat_to_dict(s, stat_names(s))
    sch = schema_of(stat)
    # numbers in a float field may serialize as integers in other encoders
    out = {"$schema": "https://json-schema.org/draft/2020-12/schema",
           "$id": "urn:linuxcnc-state-layer:emc_stat",
           "title": "EMC_STAT as published by the state layer (linuxcnc.stat fields)",
           "description": "Generated by schema/gen_emc_stat_schema.py from linuxcnc.stat; "
                          "field names as in the linuxcnc Python module.",
           **sch}
    # lengths that depend on the configuration / program, not on build constants
    props = out["properties"]
    for k in ("tool_table", "call_stack"):
        props[k].pop("minItems", None)
        props[k].pop("maxItems", None)
    # the sidecar cuts per-joint / per-axis / per-spindle arrays to the
    # configuration announced in hello (stat has the build maxima
    # EMCMOT_MAX_*; hello.stat_max carries them)
    sized = {k: "hello.joints entries (joint number = index)"
             for k in ("joint", "homed", "limit", "joint_position", "joint_actual_position")}
    sized["axis"] = "one entry per axis in axis_mask, in the order of hello.axes"
    sized["spindle"] = "hello.spindles entries"
    for k, d in sized.items():
        props[k].pop("minItems", None)
        props[k].pop("maxItems", None)
        props[k]["description"] = d
    # call_stack is empty in the main program; frames per emcmodule.cc Stat_call_stack
    props["call_stack"]["items"] = {
        "type": "object", "additionalProperties": False,
        "required": ["filename", "subname", "line"],
        "properties": {"filename": {"type": "string"}, "subname": {"type": "string"},
                       "line": {"type": "integer"}}}
    # sidecar --drop-fields may omit fields: only the always-changing beats are optional
    out["required"] = [k for k in out["required"] if k not in ("heartbeat", "taskbeat")]
    json.dump(out, sys.stdout, indent=1, sort_keys=False)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
